def _replace_once(text: str, old: str, new: str, label: str) -> str:
    count = text.count(old)
    if count != 1:
        raise ValueError(f"Expected one {label} occurrence, found {count}.")
    return text.replace(old, new, 1)


def build() -> Path:
    core = (ROOT / "src" / "phase_attention.py").read_text(encoding="utf-8")
    evaluator = (ROOT / "experiments" / "kaggle_reversal_eval.py").read_text(encoding="utf-8")

    evaluator = _replace_once(
        evaluator,
        "from src.phase_attention import apply_phase, reversal_phase\n",
        "",
        "intra-repo import",
    )
    evaluator = _replace_once(
        evaluator,
        'if __name__ == "__main__":\n    main()\n',
        "",
        "__main__ guard",
    )
    evaluator = _replace_once(
        evaluator,
        '                            f"margin={records[-1][\'margin\']:.4f}"\n'
        "                        )\n",
        '                            f"margin={records[-1][\'margin\']:.4f}"\n'
        "                        )\n"
        "                        _append_progress(records[-1])\n",
        "print block",
    )

    parts = [
        HEADER.replace("{commit}", SOURCE_COMMIT),
        core,
        MIDDLE,
        evaluator,
        PROGRESS_HOOK,
        "# ==== BEGIN Kaggle driver globals ====\n"
        "import gc\n"
        "import os\n"
        "import platform\n"
        "import subprocess\n"
        "import traceback\n"
        "from datetime import datetime, timezone\n\n"
        f'KERNEL_ID = "{KERNEL_ID}"\n'
        f'MODEL_ID = "{MODEL_ID}"\n'
        f'SOURCE_COMMIT = "{SOURCE_COMMIT}"\n'
        "SEED = 0\n"
        "ENV_INFO = {}\n\n",
        DRIVER,
    ]
    script = "".join(parts)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "kernel-metadata.json").write_text(
        json.dumps(METADATA, indent=2) + "\n", encoding="utf-8"
    )
    entry = OUT_DIR / "run_kaggle_phase_eval.py"
    entry.write_text(script, encoding="utf-8")
    print(f"Built {entry} ({len(script.splitlines())} lines)")
    print(f"Built {OUT_DIR / 'kernel-metadata.json'}")
    return entry


if __name__ == "__main__":
    build()
