def _smoke_costs(smoke_payload, lengths):
    """Measured mean forward time in ms for each target length."""
    grouped = defaultdict(list)
    for row in smoke_payload["summary"]:
        grouped[row["target_tokens"]].append(row["mean_forward_ms"])
    raw = {length: sum(values) / len(values) for length, values in grouped.items()}
    fallback = max(raw.values()) if raw else 1000.0
    return {length: max(raw.get(length, fallback), 1.0) for length in lengths}


def _plan_shards(lengths, scenarios, cases, costs, modes, n_gpus):
    """Greedy cost-balanced packing. A group is atomic: all modes stay on one GPU."""
    groups = [
        {"length": length, "scenario": scenario, "case_index": case_index}
        for length in sorted(lengths, key=lambda value: -costs[value])
        for scenario in scenarios
        for case_index in range(cases)
    ]
    shards = [[] for _ in range(n_gpus)]
    loads = [0.0] * n_gpus
    for group in groups:
        target = loads.index(min(loads))
        shards[target].append(group)
        loads[target] += costs[group["length"]] * len(modes)
    return shards, loads


def _run_workers(shards, lengths, cases, modes, work_dir):
    processes = []
    for index, shard in enumerate(shards):
        shard_path = work_dir / f"shard_{index}.json"
        shard_path.write_text(json.dumps(shard, indent=2), encoding="utf-8")
        out_path = work_dir / f"shard_{index}_results.json"
        log_path = work_dir / f"worker_{index}.log"
        args = [
            "--model", MODEL_ID,
            "--lengths", *(str(value) for value in lengths),
            "--cases", str(cases),
            "--modes", *modes,
            "--output", str(out_path),
            "--shard-file", str(shard_path),
        ]
        command = [sys.executable, str(Path(__file__).resolve()), "--worker", *args]
        env = os.environ.copy()
        env["CUDA_VISIBLE_DEVICES"] = str(index)
        env["HF_HUB_OFFLINE"] = "1"
        env["TRANSFORMERS_OFFLINE"] = "1"
        log_handle = log_path.open("w", encoding="utf-8")
        print(f"[driver] GPU {index}: {len(shard)} groups, log={log_path.name}", flush=True)
        process = subprocess.Popen(command, env=env, stdout=log_handle, stderr=subprocess.STDOUT)
        processes.append((index, process, log_handle, log_path, out_path))

    failures = []
    for index, process, log_handle, log_path, out_path in processes:
        code = process.wait()
        log_handle.close()
        print(f"[driver] worker {index} exit={code} log={log_path.name}", flush=True)
        if code != 0 or not out_path.is_file():
            failures.append(index)
    if failures:
        for index in failures:
            path = work_dir / f"worker_{index}.log"
            lines = path.read_text(encoding="utf-8").splitlines()[-40:]
            print(f"[driver] ---- worker {index} log tail ----", flush=True)
            print("\\n".join(lines), flush=True)
        raise RuntimeError(f"Workers failed: {failures}")
    return [work_dir / f"shard_{index}_results.json" for index in range(len(shards))]


